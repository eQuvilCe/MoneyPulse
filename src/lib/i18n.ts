export type TKey = keyof typeof translations.ru;

export function t(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const raw = translations[lang][key] ?? translations.ru[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
